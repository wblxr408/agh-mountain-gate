export function registerGateFonts(document) {
  const { FontFace, atob } = document.defaultView
  const faces = [
    new FontFace('AgnesGateTitle', Uint8Array.from(atob(cinzel), glyph => glyph.charCodeAt(0)), {
      weight: '400 900',
    }),
    new FontFace('AgnesGateSans', Uint8Array.from(atob(notoSansSc), glyph => glyph.charCodeAt(0)), {
      weight: '100 900',
    }),
  ]
  for (const face of faces) document.fonts.add(face)
  return () => {
    for (const face of faces) document.fonts.delete(face)
  }
}
